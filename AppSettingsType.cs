namespace Vantum.AppKit;

/// <summary>
/// Supported setting value types for app configuration.
/// </summary>
public enum AppSettingType
{
    /// <summary>String/text value</summary>
    String,

    /// <summary>Integer value</summary>
    Int,

    /// <summary>Boolean value</summary>
    Bool,

    /// <summary>Decimal/floating-point value</summary>
    Decimal,

    /// <summary>JSON object or array</summary>
    Json
}

